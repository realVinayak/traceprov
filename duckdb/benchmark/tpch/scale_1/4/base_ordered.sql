-- using default substitutions


select
	o_orderpriority,
	count(*) as order_count
from
	q4_2_orders_ordered
where
	o_orderdate >= date '1993-07-01'
	and o_orderdate < date '1993-07-01' + interval '3' month
	and exists (
		select
			*
		from
			q4_1_lineitem_ordered
		where
			l_orderkey = o_orderkey
			and l_commitdate < l_receiptdate
	)
group by
	o_orderpriority
order by
	o_orderpriority;
